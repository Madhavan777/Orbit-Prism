"""EXPERIMENTAL confidence-aware priority scoring for ORBIT-PRISM (floods and fires only).

Calculates a priority score (not a danger or risk measure) from:
  - Event probability and severity
  - Spatial extent and exposure (population/infrastructure), when known
  - Sensor confidence and cloud obscuration
  - A per-hazard urgency multiplier

All weights and multipliers are unvalidated assumptions. No exposure data is loaded, so
exposure is normally UNKNOWN and is represented as such rather than as zero.
"""

from dataclasses import dataclass
from typing import Optional, List, Dict, Any
import numpy as np

from src.disasters.registry import DisasterCategory, DisasterRegistry


@dataclass
class DisasterEvent:
    """Standardized event packet generated by edge detection models."""
    tile_id: str
    category: DisasterCategory
    p_event: float            # Model probability in [0.0, 1.0]
    severity: float           # Physical hazard intensity in [0.0, 1.0]
    extent: float             # Spatial coverage fraction in [0.0, 1.0]
    cloud_frac: float = 0.0   # Cloud cover fraction in [0.0, 1.0]
    exposure_score: Optional[float] = None  # Population/infrastructure exposure in [0.0, 1.0], None = UNKNOWN
    sensor_reliability: float = 0.95        # Nominal sensor reliability factor
    latitude: Optional[float] = None
    longitude: Optional[float] = None


@dataclass
class RiskAssessment:
    """Comprehensive risk profile and priority decision for a disaster event."""
    tile_id: str
    category: DisasterCategory
    priority_score: float     # Overall priority in [0.0, 100.0]
    confidence: float         # Confidence in [0.0, 1.0]
    hazard_score: float       # Physical hazard index in [0.0, 1.0]
    vulnerability_score: float  # Effective exposure index in [0.0, 1.0]
    is_exposure_unknown: bool
    urgency_multiplier: float
    raw_event: DisasterEvent

    def to_dict(self) -> Dict[str, Any]:
        return {
            "tile_id": self.tile_id,
            "disaster_type": self.category.value,
            "p_event": round(self.raw_event.p_event, 4),
            "severity": round(self.raw_event.severity, 4),
            "extent": round(self.raw_event.extent, 4),
            "exposure_score": "UNKNOWN" if self.is_exposure_unknown else round(self.vulnerability_score, 4),
            "confidence": round(self.confidence, 4),
            "priority_score": round(self.priority_score, 2),
            "urgency": self.urgency_multiplier
        }


class RiskEngine:
    """Calculates confidence-aware multi-disaster priority scores."""

    def __init__(
        self,
        weight_hazard: float = 0.50,
        weight_vulnerability: float = 0.50,
        unknown_exposure_default: float = 0.50,
        unknown_exposure_confidence_penalty: float = 0.25
    ):
        """Initialize RiskEngine.

        Args:
            weight_hazard: Weight for (p_event * severity).
            weight_vulnerability: Weight for (extent * exposure).
            unknown_exposure_default: Assigned default exposure when missing (prevents assuming 0 risk).
            unknown_exposure_confidence_penalty: Degradation of confidence when exposure is unknown.
        """
        self.w_hazard = weight_hazard
        self.w_vuln = weight_vulnerability
        self.unknown_exp_default = unknown_exposure_default
        self.unknown_exp_penalty = unknown_exposure_confidence_penalty

    def assess_event(self, event: DisasterEvent) -> RiskAssessment:
        """Assess a single disaster event and compute its priority score."""
        profile = DisasterRegistry.get_profile(event.category)
        urgency = profile.urgency_multiplier

        # 1. Base Hazard Intensity
        hazard = float(np.clip(event.p_event * event.severity, 0.0, 1.0))

        # 2. Vulnerability & Exposure Handling (explicit UNKNOWN handling)
        if event.exposure_score is None or event.exposure_score < 0:
            is_unknown = True
            vulnerability = self.unknown_exp_default
            exp_confidence_factor = (1.0 - self.unknown_exp_penalty)
        else:
            is_unknown = False
            vulnerability = float(np.clip(event.exposure_score, 0.0, 1.0))
            exp_confidence_factor = 1.0

        # Exposure footprint combines extent with demographic/asset vulnerability
        impact_footprint = float(np.clip(event.extent * vulnerability, 0.0, 1.0))

        # 3. Confidence Estimation
        # Decreases with cloud cover and missing metadata
        cloud_factor = max(0.0, 1.0 - (0.8 * event.cloud_frac))
        confidence = float(np.clip(
            event.sensor_reliability * cloud_factor * exp_confidence_factor,
            0.05,
            1.0
        ))

        # 4. Composite Risk & Priority Calculation
        base_risk = (self.w_hazard * hazard) + (self.w_vuln * impact_footprint)
        # Scaled by urgency and confidence into [0.0, 100.0]
        # Max theoretical score: 1.0 * (max_urgency ~2.4) * 40 ~= 100
        raw_priority = base_risk * confidence * urgency * 40.0
        priority_score = float(np.clip(raw_priority, 0.0, 100.0))

        return RiskAssessment(
            tile_id=event.tile_id,
            category=event.category,
            priority_score=priority_score,
            confidence=confidence,
            hazard_score=hazard,
            vulnerability_score=vulnerability,
            is_exposure_unknown=is_unknown,
            urgency_multiplier=urgency,
            raw_event=event
        )

    def rank_events(self, events: List[DisasterEvent]) -> List[RiskAssessment]:
        """Assess and rank a collection of disaster events in descending priority order."""
        assessments = [self.assess_event(e) for e in events]
        # Sort descending by priority_score, breaking ties by confidence
        assessments.sort(key=lambda a: (a.priority_score, a.confidence), reverse=True)
        return assessments
